// Builds eval/benign_top500.txt: the 500 most downloaded npm packages, each
// pinned to its current `latest` version, for the false-positive evaluation.
//
// Ranking source: the `topDownload` list of the npm-high-impact package
// (https://github.com/wooorm/npm-high-impact), which is sorted by weekly
// downloads at the time its author last refreshed it. We read that file as
// plain text and extract the quoted names with a regular expression; the
// package's code is never imported or executed.
//
// Versions: `dist-tags.latest` from the npm registry on the day this script
// runs. Both dates are written in the header.
//
// Run with Node 22.18 or later:  node scripts/build_top500.ts [count]

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "eval", "benign_top500.txt");
const count = Number(process.argv[2] ?? 500);
const REGISTRY = "https://registry.npmjs.org";

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function getJson(
  url: string,
  accept = "application/json",
): Promise<unknown> {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url, {
      headers: { accept },
      signal: AbortSignal.timeout(30_000),
    });
    if (res.ok) return res.json();
    if (attempt >= 4 || (res.status !== 429 && res.status < 500)) {
      throw new Error(`HTTP ${res.status} for ${url}`);
    }
    await sleep(2000 * 2 ** attempt);
  }
}

type Packument = {
  "dist-tags": Record<string, string>;
  time?: Record<string, string>;
  versions: Record<string, { dist: { tarball: string } }>;
};

async function main(): Promise<void> {
  // 1. The ranking: npm-high-impact's topDownload list.
  const meta = (await getJson(`${REGISTRY}/npm-high-impact`)) as Packument;
  const nhiVersion = meta["dist-tags"].latest as string;
  const nhiPublished = meta.time?.[nhiVersion] ?? "unknown";
  const tarball = meta.versions[nhiVersion]?.dist.tarball as string;
  const work = mkdtempSync(join(tmpdir(), "lockwatch-top500-"));
  let names: string[];
  try {
    const res = await fetch(tarball);
    writeFileSync(join(work, "nhi.tgz"), Buffer.from(await res.arrayBuffer()));
    // `tar` only unpacks the archive; nothing from it is run.
    execFileSync("tar", ["-xzf", "nhi.tgz", "package/lib/top-download.js"], {
      cwd: work,
    });
    const text = readFileSync(
      join(work, "package/lib/top-download.js"),
      "utf8",
    );
    names = [...text.matchAll(/^\s*'([^']+)',?$/gm)].map((m) => m[1] as string);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
  if (names.length < count)
    throw new Error(`only ${names.length} names in the ranking`);

  // 2. Current latest version of each (small "abbreviated" documents).
  const lines: string[] = [];
  for (const name of names.slice(0, count)) {
    const doc = (await getJson(
      `${REGISTRY}/${name.replace("/", "%2f")}`,
      "application/vnd.npm.install-v1+json",
    )) as Packument;
    const latest = doc["dist-tags"].latest;
    if (!latest) throw new Error(`${name} has no latest version`);
    lines.push(`${name}@${latest}`);
  }

  const today = new Date().toISOString().slice(0, 10);
  const header = [
    "# The 500 most downloaded npm packages, pinned to their latest version.",
    `# ranking: npm-high-impact@${nhiVersion} topDownload list (published ${nhiPublished})`,
    `# versions: dist-tags.latest from ${REGISTRY} on ${today}`,
    "# generated by scripts/build_top500.ts; one name@version per line, most downloaded first",
  ];
  writeFileSync(outPath, [...header, ...lines, ""].join("\n"));
  console.log(`wrote ${lines.length} packages to ${outPath}`);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
